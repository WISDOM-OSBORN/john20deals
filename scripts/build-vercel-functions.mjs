// Generates self-contained CommonJS handlers in /api (Vercel) for the flows
// the frontend calls through `/.netlify/functions/*` in production.
//
// Vercel compiles /api/*.ts entries but (observed) does not transpile the
// `netlify/functions/**` modules they import, causing FUNCTION_INVOCATION_FAILED.
// This script bundles each handler + the shared adapter into a single self-
// contained .mjs file in /api (ESM, default export), which Vercel deploys as a
// serverless function at /api/<route>. vercel.json rewrites
// `/.netlify/functions/:splat` -> `/api/:splat` so the production call sites
// keep working without code changes.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'api');
const entriesDir = join(root, 'scripts', '.entries');

// Route name (Vercel function path) => handler source file (repo root).
// Route names MUST match `.netlify/functions/<name>` call sites.
const FNS = {
  'upload-url': 'netlify/functions/upload-url',
  'submit-swap': 'netlify/functions/submit-swap',
  'submit-sell': 'netlify/functions/submit-sell',
  'submit-repair': 'netlify/functions/submit-repair',
};

rmSync(entriesDir, { recursive: true, force: true });
mkdirSync(entriesDir, { recursive: true });

try {
  for (const [route, source] of Object.entries(FNS)) {
    const entry = join(entriesDir, `${route}.ts`);
    writeFileSync(
      entry,
      [
        `import { handler } from '${root.replace(/\\/g, '/')}/${source}';`,
        `import { runHandler } from '${root.replace(/\\/g, '/')}/api/_lib/adapter';`,
        '',
        'export default async function (req: any, res: any) {',
        '  return runHandler(handler as any, req as any, res as any);',
        '}',
        '',
      ].join('\n')
    );

    // The dedicated ESM bundle (upload-url) pulls in @smithy/node-http-handler,
    // whose CJS code does `require("node:https")` at module init. esbuild emits
    // that as a dynamic require, which is fatal in Vercel's pure-ESM runtime
    // (no `require`). Injecting a `require` bound to createRequire makes those
    // dynamic requires of node builtins work. Harmless for bundles that don't
    // need it.
    const requireShim =
      '// generated by scripts/build-vercel-functions.mjs - do not edit\n' +
      "import { createRequire as __j20createRequire } from 'node:module';\n" +
      'const require = __j20createRequire(import.meta.url);\n';

    await build({
      entryPoints: [entry],
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node18',
      outfile: join(apiDir, `${route}.mjs`),
      banner: { js: requireShim },
      logLevel: 'warning',
    });
    console.log(`built api/${route}.mjs`);
  }
} finally {
  rmSync(entriesDir, { recursive: true, force: true });
}

// Remove stale generated functions for routes that no longer exist.
for (const file of readdirSync(apiDir)) {
  if (file.startsWith('.') || !file.endsWith('.mjs')) continue;
  const route = file.replace(/\.mjs$/, '');
  if (!FNS[route]) rmSync(join(apiDir, file));
}
console.log('vercel functions generated');