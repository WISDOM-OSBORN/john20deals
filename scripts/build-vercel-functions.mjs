// Generates self-contained CommonJS handlers in /api for Vercel.
//
// Vercel compiles /api/*.ts entries but (observed) does not transpile the
// netlify/functions/** modules they import, causing FUNCTION_INVOCATION_FAILED.
// This script bundles every handler + the shared adapter into a single .cjs
// file in /api so Vercel deploys truly self-contained functions that also
// handle both Node-style (VercelRequest) and Web Request invocations.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'api');
const entriesDir = join(root, 'scripts', '.entries');

// Route name => handler source file (relative to repo root).
const FNS = {
  'user-ops': 'netlify/functions/user-ops',
  'admin-ops': 'netlify/functions/admin-ops',
  'submit-order': 'netlify/functions/submit-order',
  'submit-swap': 'netlify/functions/submit-swap',
  'submit-sell': 'netlify/functions/submit-sell',
  'submit-repair': 'netlify/functions/submit-repair',
  'upload': 'netlify/functions/upload-url',
};

rmSync(entriesDir, { recursive: true, force: true });
mkdirSync(entriesDir, { recursive: true });

try {
  for (const [route, source] of Object.entries(FNS)) {
    const entry = join(entriesDir, `${route}.ts`);
    writeFileSync(
      entry,
      [
        `import { handler } from '${root.replace(/\\/g, '/')}/${source}';`,
        `import { runHandler } from '${root.replace(/\\/g, '/')}/api/_lib/adapter';`,
        '',
        'export default async function (req: any, res: any) {',
        '  return runHandler(handler as any, req as any, res as any);',
        '}',
        '',
      ].join('\n')
    );

    await build({
      entryPoints: [entry],
      bundle: true,
      platform: 'node',
      format: 'cjs',
      target: 'node18',
      outfile: join(apiDir, `${route}.cjs`),
      banner: { js: '// generated by scripts/build-vercel-functions.mjs - do not edit' },
      footer: { js: 'module.exports = module.exports ? module.exports.default : module.exports;' },
      logLevel: 'warning',
    });
    console.log(`built api/${route}.cjs`);
  }
} finally {
  rmSync(entriesDir, { recursive: true, force: true });
}

// Remove stale generated cjs for routes that no longer exist.
for (const file of readdirSync(apiDir)) {
  if (file.startsWith('.') || !file.endsWith('.cjs')) continue;
  const route = file.replace(/\.cjs$/, '');
  if (!FNS[route]) rmSync(join(apiDir, file));
}
console.log('vercel functions generated');